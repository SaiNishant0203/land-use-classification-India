"""
Latent segmentation logit of development, 2017 -> 2023 (pixel level).

Instead of fixing the contexts by hand (density tertiles, distance rings: section D of
22_choice_models.py), the model finds K segments of land whose development responds differently
to proximity. Segment membership is a multinomial logit on context variables (surrounding
building cover in 2017 and distance to the old CBD); within each segment, development is a
binary logit on the proximity variables and controls of the main specification.
K = 1, 2, 3 are compared by BIC. Estimation reuses latent_segmentation() from
scripts/overnight/m2_choice_models.py (PyTorch, L-BFGS, several random starts, Hessian SEs).

Output: outputs/lu/choice_latent/ (fit.csv, coefs.csv, REPORT.md)
"""
import sys
import numpy as np, pandas as pd
import importlib.util as iu
from lu_common import LU, LUOUT, ROOT, log

sys.path.insert(0, str(ROOT / "scripts" / "overnight"))
def _load(n, f):
    s = iu.spec_from_file_location(n, f); m = iu.module_from_spec(s); s.loader.exec_module(m); return m

m2 = _load("m2", ROOT / "scripts/overnight/m2_choice_models.py")
td = _load("td", ROOT / "scripts/lu/21_transition_data.py")
cm = _load("cm", ROOT / "scripts/lu/22_choice_models.py")
OUT = LUOUT / "choice_latent"; OUT.mkdir(exist_ok=True)
Y0, Y1 = (int(a) for a in sys.argv[1:3]) if len(sys.argv) > 2 else (2017, 2023)


def main():
    D = td.period(pd.read_parquet(LU / "transition_panel.parquet"), Y0, Y1)
    d, Z, mu, sd = cm.prep(D)
    y = (d.outcome.values > 0).astype(float)
    memb = pd.DataFrame({"cov_61_t0": Z["cov_61_t0"], "ln_d_cbd": Z["d_cbd_abids"]})
    X = Z.drop(columns=["cov_61_t0"])                      # density moves to the membership model
    A = cm.fit_logit(y, X, d.tile.values)
    init = A.params.values
    fits = []
    for K in (1, 2, 3):
        r = m2.latent_segmentation(X.values, y, memb.values, K, starts=6, init_beta=init, seed=K)
        fits.append(r)
        log(f"K={K}: LL={r['LL']:.1f} BIC={r['BIC']:.1f} shares={np.round(r['shares'], 3)} hessian_ok={r['hessian_ok']}")
    F = pd.DataFrame([{"K": r["K"], "LL": r["LL"], "params": r["k"], "AIC": r["AIC"], "BIC": r["BIC"],
                       "shares": np.round(r["shares"], 3).tolist(), "hessian_ok": r["hessian_ok"]} for r in fits])
    F.to_csv(OUT / "fit.csv", index=False)
    best = min(fits, key=lambda r: r["BIC"])
    names = ["const"] + [cm.LABEL.get(c, c) for c in X.columns]
    order = np.argsort(-best["shares"])
    rows = {}
    for rank, k in enumerate(order):
        col = f"segment {rank + 1} ({best['shares'][k]:.0%})"
        b, s = best["B"][k], best["SEB"][k]
        z = np.where(s > 0, b / np.where(s > 0, s, 1), np.nan)
        star = np.where(np.abs(z) > 3.29, "***", np.where(np.abs(z) > 2.58, "**", np.where(np.abs(z) > 1.96, "*", "")))
        rows[col] = [f"{bi:.3f}{st}" for bi, st in zip(b, star)]
    C = pd.DataFrame(rows, index=names); C.to_csv(OUT / "coefs.csv")
    mem = ""
    if best["G"] is not None:
        G = pd.DataFrame(best["G"], columns=["const", "building cover 610 m (start)", "ln dist. to old CBD"],
                         index=[f"segment {i + 2} vs 1 (unordered)" for i in range(best["G"].shape[0])])
        G.to_csv(OUT / "membership.csv"); mem = G.round(3).to_markdown()
    md = [f"# Latent segmentation logit of development, {Y0} → {Y1}\n",
          "*Auto-generated by `scripts/lu/25_latent_segmentation.py`.*\n",
          f"{len(d):,} undeveloped pixels; outcome = developed by {Y1}. Segment membership depends on surrounding "
          "building cover and distance to the old CBD. Standardised variables; negative distance coefficient = closer → more likely.\n",
          "## Model selection\n", F.round(1).to_markdown(index=False), f"\nBIC selects **K = {best['K']}**.\n",
          "## Segment coefficients (z-test stars from Hessian SEs, not clustered)\n", C.to_markdown(), "\n"]
    if mem:
        md += ["## Membership model (raw segment order)\n", mem, "\n"]
    (OUT / "REPORT.md").write_text("\n".join(md), encoding="utf-8")
    log(f"wrote {OUT / 'REPORT.md'}")


if __name__ == "__main__":
    main()
