"""
Are the proximity effects stable over time? Same pixels, same code, two non-overlapping periods
(2017->2020, 2020->2023) plus the full period (2017->2023).

For each period: binary logit and MNL with the main specification of 22_choice_models.py
(each period's road network and metro stations as they were at its start year), and observed
transition rates by distance band.

Output: outputs/lu/choice_periods/  (coef_binary.csv, coef_mnl.csv, observed_by_period.png, REPORT.md)
"""
import numpy as np, pandas as pd
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
import importlib.util as iu
from lu_common import LU, LUOUT, log

def _load(n, f):
    s = iu.spec_from_file_location(n, LU.parents[2] / "scripts/lu" / f); m = iu.module_from_spec(s)
    s.loader.exec_module(m); return m

td = _load("td", "21_transition_data.py")
cm = _load("cm", "22_choice_models.py")
OUT = LUOUT / "choice_periods"; OUT.mkdir(exist_ok=True)
PERIODS = [(2017, 2020), (2020, 2023), (2017, 2023)]


def cell(fit, i, eq=None):
    p = fit.params.iloc[i] if eq is None else fit.params.iloc[i, eq]
    pv = fit.pvalues.iloc[i] if eq is None else fit.pvalues.iloc[i, eq]
    s = "***" if pv < .001 else "**" if pv < .01 else "*" if pv < .05 else ""
    return f"{p:.3f}{s}"


def main():
    import os
    global OUT
    if os.environ.get("DRY"):
        OUT = LUOUT / "choice_periods_dryrun"; OUT.mkdir(exist_ok=True)
    P = pd.read_parquet(LU / ("transition_panel_dryrun.parquet" if os.environ.get("DRY") else "transition_panel.parquet"))
    binr, mres, mnon, stats, obs = {}, {}, {}, [], {}
    for y0, y1 in PERIODS:
        D = td.period(P, y0, y1)
        d, Z, mu, sd = cm.prep(D)
        y3 = d.outcome.values; yb = (y3 > 0).astype(int); g = d.tile.values
        A = cm.fit_logit(yb, Z, g); B, _ = cm.fit_mnl(y3, Z, g)
        key = f"{y0}->{y1}"
        names = ["const"] + list(Z.columns)
        binr[key] = [cell(A, i) for i in range(len(names))]
        mres[key] = [cell(B, i, 0) for i in range(len(names))]
        mnon[key] = [cell(B, i, 1) for i in range(len(names))]
        yrs = y1 - y0
        stats.append({"period": key, "n_undeveloped": len(d), "developed_%": 100 * yb.mean(),
                      "per_year_%": 100 * (1 - (1 - yb.mean()) ** (1 / yrs)),
                      "residential_%": 100 * (y3 == 1).mean(), "non_res_%": 100 * (y3 == 2).mean(),
                      "pseudoR2_binary": A.prsquared, "pseudoR2_mnl": B.prsquared})
        for v, bins in (("d_employment", [0, 2.5, 5, 7.5, 10, 15, 20, 25, 30, 40, 50, 100]),
                        ("d_orr_access", [0, 1, 2, 3, 5, 7.5, 10, 15, 20, 30, 50]),
                        ("d_major_road_t0", [0, .1, .25, .5, 1, 2, 3, 5, 10])):
            gr = d.groupby(pd.cut(d[v], bins), observed=True).outcome
            obs[(key, v)] = pd.DataFrame({"res": gr.apply(lambda s: (s == 1).mean()),
                                          "nonres": gr.apply(lambda s: (s == 2).mean()), "n": gr.size()})
        log(f"{key}: n={len(d):,}, developed {yb.mean():.2%}, binary R2 {A.prsquared:.3f}")
    lab = [cm.LABEL.get(n, n) for n in names]
    T = {"binary": pd.DataFrame(binr, index=lab), "mnl_res": pd.DataFrame(mres, index=lab),
         "mnl_nonres": pd.DataFrame(mnon, index=lab)}
    for k, v in T.items():
        v.to_csv(OUT / f"coef_{k}.csv")
    S = pd.DataFrame(stats); S.to_csv(OUT / "period_stats.csv", index=False)

    fig, ax = plt.subplots(2, 3, figsize=(15, 8))
    cols = {"2017->2020": "#1f77b4", "2020->2023": "#ff7f0e", "2017->2023": "#7f7f7f"}
    xl = {"d_employment": "distance to HITEC City / FD (km)", "d_orr_access": "distance to ORR interchange (km)",
          "d_major_road_t0": "distance to major road, start-year network (km)"}
    for j, v in enumerate(xl):
        for i, (c, nm) in enumerate((("nonres", "became non-residential"), ("res", "became residential"))):
            a = ax[i, j]
            for key, col in cols.items():
                t = obs[(key, v)]; yrs = int(key[-4:]) - int(key[:4])
                mid = [(b.left + b.right) / 2 for b in t.index]
                a.plot(mid, 100 * t[c] / yrs, "o-", color=col, label=f"{key} (per year)", lw=1.5 if key != "2017->2023" else 1,
                       ls="-" if key != "2017->2023" else "--")
            a.set_xlabel(xl[v]); a.set_ylabel(f"% {nm} per year"); a.grid(alpha=.3)
    ax[0, 0].legend()
    fig.suptitle("Observed annual transition rates by proximity, by period (same pixels)")
    fig.tight_layout(); fig.savefig(OUT / "observed_by_period.png", dpi=150); plt.close(fig)

    md = ["# Stability of proximity effects over time\n", "*Auto-generated by `scripts/lu/24_period_compare.py`.*\n",
          "Same pixels and code in every period. Each period uses the road network and metro stations "
          "as they were at its own start year. A negative distance coefficient means closer → more likely.\n",
          "## Development rates\n", S.round(3).to_markdown(index=False), "\n",
          "## Binary logit (developed)\n", T["binary"].to_markdown(), "\n",
          "## MNL: residential vs none\n", T["mnl_res"].to_markdown(), "\n",
          "## MNL: non-residential vs none\n", T["mnl_nonres"].to_markdown(), "\n",
          "![observed](observed_by_period.png)\n"]
    (OUT / "REPORT.md").write_text("\n".join(md), encoding="utf-8")
    log(f"wrote {OUT / 'REPORT.md'}")


if __name__ == "__main__":
    main()
