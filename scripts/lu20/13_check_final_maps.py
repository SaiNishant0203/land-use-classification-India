"""
Checks of the final maps from 12_final_maps.py against the current production maps (06_maps.py,
`year` model, one seed): hand-label macro-F1 for 2023 (confidence <= 2, stratum-weighted, paired
stratified bootstrap), class shares per year, and year-to-year stability inside HMDA. A last section
covers the final maps alone for every year 2017-2023 (production maps exist for 2017/2020/2023 only).

Expected from 11_retrain_variants.py: cw_prior 5-seed mean-probability map 0.651 vs base 0.634.

Usage: python 13_check_final_maps.py
Output: outputs/lu20/maps_final/CHECK.md, check_scores.csv, check_maps.csv
"""
import importlib
import numpy as np, pandas as pd, rasterio
from common20 import *
import features20 as FX

E = importlib.import_module("05_eval")
F = OUT / "maps_final"
MAPS = {"final (cw_prior, 5 seeds)": lambda y: F / f"landuse_{y}_20m.tif",
        "production (base, 1 seed)": lambda y: OUT / "maps" / f"landuse_{y}_20m_year.tif"}


def read(fp):
    with rasterio.open(fp) as r:
        return r.read(1)


def annual(ins):
    """Class shares and one-year change of the final maps, all years."""
    a = {y: read(F / f"landuse_{y}_20m.tif")[ins] for y in ALL_YEARS}
    rows = []
    for i, y in enumerate(ALL_YEARS):
        r = {"year": y, **{n: (a[y] == c).mean() for c, n in zip(CL, ["res", "nonres", "water", "trees", "open"])}}
        if i:
            p, q = a[ALL_YEARS[i - 1]], a[y]
            r.update({"changed": (p != q).mean(), "built_to_open": (np.isin(p, [1, 2]) & np.isin(q, [4, 5])).mean(),
                      "open_to_built": (np.isin(p, [4, 5]) & np.isin(q, [1, 2])).mean()})
        if 0 < i < len(ALL_YEARS) - 1:
            p, q, n = a[ALL_YEARS[i - 1]], a[y], a[ALL_YEARS[i + 1]]
            r["flip-flop"] = ((p == n) & (q != p)).mean()
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(F / "check_annual.csv", index=False)
    log("\n" + t.round(4).to_string(index=False))
    return t


def main():
    A = {k: {y: read(f(y)) for y in YEARS} for k, f in MAPS.items()}
    grid = FX.open_grid(2023)
    v = E.hand_labels(grid); v = v[v.confidence.fillna(3) <= 2].reset_index(drop=True)
    inmap = np.all([a[2023].ravel()[v.flat.values] > 0 for a in A.values()], 0)   # 1 point lies just outside the HMDA mask
    log(f"{(~inmap).sum()} hand cells outside the mapped area, dropped: pid {v.pid[~inmap].tolist()}")
    v = v[inmap].reset_index(drop=True)
    W = pd.read_csv(LUP / "validation_strata.csv", index_col=0)["weight"].to_dict()
    ref, st = v.true_class.values, v.stratum.values
    pred = {k: a[2023].ravel()[v.flat.values] for k, a in A.items()}
    bs = E.boot(ref, pred, st, W)
    rows = []
    for k, p in pred.items():
        mf, f1, ua, pa = E.weighted(ref, p, st, W)
        rows.append({"map": k, "n": len(ref), "macro_F1": mf, "lo": np.percentile(bs[k], 2.5), "hi": np.percentile(bs[k], 97.5),
                     **{f"F1_{c}": f1[c - 1] for c in CL}, "UA_2": ua[1], "PA_2": pa[1]})
    k0, k1 = list(pred)
    d = bs[k0] - bs[k1]
    sc = pd.DataFrame(rows)
    pair = f"{k0} minus {k1}: {sc.macro_F1[0] - sc.macro_F1[1]:+.3f} [{np.percentile(d, 2.5):+.3f}, {np.percentile(d, 97.5):+.3f}]"
    log("\n" + sc.round(3).to_string(index=False) + "\n" + pair)

    ins = A[k0][2023] > 0
    mrows = []
    for k, a in A.items():
        for y in YEARS:
            c = a[y][ins]
            mrows.append({"map": k, "stat": f"share {y}", **{f"c{i}": (c == i).mean() for i in CL}})
        x, y2, z = (a[y][ins] for y in YEARS)
        for (p, q, n) in ((x, y2, "2017-2020"), (y2, z, "2020-2023")):
            mrows.append({"map": k, "stat": f"changed {n}", "c1": (p != q).mean(),
                          "c2": (np.isin(p, [1, 2]) & np.isin(q, [4, 5])).mean(),
                          "c3": (np.isin(p, [4, 5]) & np.isin(q, [4, 5]) & (p != q)).mean()})
        mrows.append({"map": k, "stat": "flip-flop 2017-2020-2023", "c1": ((x == z) & (y2 != x)).mean()})
    mp = pd.DataFrame(mrows)
    sc.to_csv(F / "check_scores.csv", index=False); mp.to_csv(F / "check_maps.csv", index=False)
    log("\n" + mp.round(4).to_string(index=False))
    txt = f"""# Final maps: check against the production maps

Auto-generated by `scripts/lu20/13_check_final_maps.py`.

## Hand labels, 2023 (confidence <= 2, stratum-weighted, 95% stratified bootstrap)

{E.md(sc)}

Paired: {pair}

## Class shares and stability inside HMDA

`share` rows: c1–c5 are class shares (1 res, 2 non-res, 3 water, 4 trees, 5 open).
`changed` rows: c1 = any class change, c2 = built → trees/open, c3 = trees ↔ open.

{E.md(mp, 4)}

## Final maps, every year 2017–2023

`changed` = any class change from the previous year; `built_to_open` (built → trees/open) and `open_to_built` are
shares of all HMDA cells; `flip-flop` = class differs from the previous year and returns to it the
next year.

{E.md(annual(ins), 4)}
"""
    (F / "CHECK.md").write_text(txt, encoding="utf-8")
    log(f"wrote {F / 'CHECK.md'}")


if __name__ == "__main__":
    main()
