"""
Hand-label scores for the 2023 maps and the summary RESULTS.md.

Hand labels (325-point test set, confidence <= 2; also without road pixels): each model predicts the
20 m cell containing the test point from 2023 inputs. Scored with the stratified estimator of
07_eval_handlabels.py (Stehman 2014; strata are OSM/Dynamic World based, independent of every map),
95% intervals and paired differences from a stratified bootstrap (1,000 draws, same draws for all models).

Also: how many 2023 training cells change label when the OSM is dated (31 Dec 2023) instead of the
September 2026 download.

Usage: python 05_eval.py
Output: outputs/lu20/handlabel_scores.csv, handlabel_paired.csv, label_change_2023.csv, RESULTS.md
"""
import pickle
import numpy as np, pandas as pd, geopandas as gpd
from pyproj import Transformer
from common20 import *
import features20 as FX

B = 1000


def weighted(ref, pred, strata, W):
    P = np.zeros((5, 5))
    for h, w in W.items():
        m = strata == h
        if m.sum():
            P += w * np.bincount((pred[m] - 1) * 5 + (ref[m] - 1), minlength=25).reshape(5, 5) / m.sum()
    ua = np.divide(np.diag(P), P.sum(1), out=np.zeros(5), where=P.sum(1) > 0)
    pa = np.divide(np.diag(P), P.sum(0), out=np.zeros(5), where=P.sum(0) > 0)
    f1 = np.divide(2 * ua * pa, ua + pa, out=np.zeros(5), where=(ua + pa) > 0)
    return f1.mean(), f1, ua, pa


def boot(ref, preds, strata, W, seed=0):
    rng = np.random.default_rng(seed)
    idx = [np.nonzero(strata == h)[0] for h in np.unique(strata)]
    out = {k: [] for k in preds}
    for _ in range(B):
        ii = np.concatenate([rng.choice(ix, len(ix)) for ix in idx if len(ix)])
        for k, p in preds.items():
            out[k].append(weighted(ref[ii], p[ii], strata[ii], W)[0])
    return {k: np.array(v) for k, v in out.items()}


def md(df, nd=3):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{nd}f}")
    return "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n" + \
        "\n".join("| " + " | ".join(map(str, r)) + " |" for r in df.values)


def hand_labels(grid):
    meta = grid["meta"]
    v = gpd.read_file(LUP / "validation_points.gpkg", layer="validation_pixels")
    v = v.merge(pd.read_csv(LUP / "validation_key.csv")[["pid", "stratum", "lon", "lat"]], on="pid", suffixes=("_g", ""))
    v = v[v.true_class.notna()].copy(); v["true_class"] = v.true_class.astype(int)
    x, y = Transformer.from_crs(4326, 32644, always_xy=True).transform(v.lon.values, v.lat.values)
    r = np.floor((meta["maxy"] - y) / CELL).astype(int); c = np.floor((x - meta["minx"]) / CELL).astype(int)
    ok = (r >= 0) & (r < meta["ny"]) & (c >= 0) & (c < meta["nx"])
    v = v[ok].copy(); v["flat"] = r[ok] * meta["nx"] + c[ok]
    return v.sort_values("flat").reset_index(drop=True)


def label_change(grid):
    """Majority label of each >=50%-labelled 2023 cell under 2026 OSM vs OSM dated 31 Dec 2023."""
    def maj(name):
        L = np.stack([np.array(grid[name][c]) for c in range(6)]).astype(np.int16)
        lab = L[1:].argmax(0) + 1
        lab[(L[1:].sum(0) / (K * K) < MIN_LFRAC) | ~np.array(grid["valid"])] = 0
        return lab
    old, new = maj("labc_osm2026"), maj("labc")
    m = (old > 0) | (new > 0)
    ct = pd.crosstab(pd.Series(old[m], name="OSM 2026 label"), pd.Series(new[m], name="OSM 2023 label"))
    names = {0: "unlabelled", 1: "res", 2: "non-res", 3: "water", 4: "forest", 5: "open"}
    return ct.rename(index=names, columns=names)


def main():
    rep = ["# 20 m land-use model with year-dated OSM labels\n",
           "Auto-generated by `scripts/lu20/05_eval.py`. 53 physical features, 20 m cells, LightGBM with the "
           "repo's settings. Training labels for year *y* use OSM as mapped on 31 December *y* "
           "(Geofabrik dated snapshots india-180101, india-210101, southern-zone-240101); before this, every "
           "model used OSM downloaded in September 2026.\n",
           "Models: `year_<y>` is trained on year *y* only; `pooled` on all years together (one model for every "
           "year); `osm2026_2023` is the control, 2023 inputs with the old undated labels.\n"]
    if (OUT / "osm_counts.csv").exists():
        oc = pd.read_csv(OUT / "osm_counts.csv")
        rep += ["## OSM as mapped at the end of each year\n", md(oc.pivot(index="tag", columns="year", values="polygons")
                                                              .reset_index().rename_axis(None, axis=1)) + "\n",
                "Polygons per tag (any value of the tags the labels use).\n"]
    ls = [pd.read_csv(OUT / f"label_stats_{y}.csv").drop(columns="tile").sum().rename(y) for y in YEARS
          if (OUT / f"label_stats_{y}.csv").exists()]
    if ls:
        t = pd.DataFrame(ls).rename(columns={"c0": "unlabelled", "c1": "res", "c2": "non-res", "c3": "water",
                                             "c4": "forest", "c5": "open"})
        rep += ["## Labelled 10 m pixels per year\n", md(t.reset_index().rename(columns={"index": "year"})) + "\n"]

    hs, hp = None, None
    if 2023 in years_done("grid") and (OUT / "models" / "year_2023.pkl").exists():
        grid = FX.open_grid(2023)
        ct = label_change(grid)
        ct.to_csv(OUT / "label_change_2023.csv")
        both = ct.drop(index="unlabelled", columns="unlabelled", errors="ignore")
        same = sum(both.loc[i, i] for i in both.index if i in both.columns)
        rep += ["## 2023 training cells: undated (2026) vs dated (2023) OSM\n",
                md(ct.reset_index()) + "\n",
                f"Of cells labelled under both, **{1 - same / both.values.sum():.1%}** change class. "
                f"Cells labelled only under 2026 OSM: {int(ct.loc[ct.index != 'unlabelled', 'unlabelled'].sum()) if 'unlabelled' in ct.columns else 0:,}; "
                f"only under 2023 OSM: {int(ct.loc['unlabelled'].drop('unlabelled', errors='ignore').sum()) if 'unlabelled' in ct.index else 0:,}.\n"]
        v = hand_labels(grid)
        names, X = FX.extract(grid, v.flat.values)
        X = pd.DataFrame(X, columns=names)
        W = pd.read_csv(LUP / "validation_strata.csv", index_col=0)["weight"].to_dict()
        mods = [m for m in ["year_2023", "pooled", "osm2026_2023"] if (OUT / "models" / f"{m}.pkl").exists()]
        pred = {}
        for mname in mods:
            m, feats = pickle.load(open(OUT / "models" / f"{mname}.pkl", "rb"))
            pred[mname] = m.predict(X[feats]).astype(int)
        rows, prs = [], []
        subsets = {"confidence<=2 (headline)": (v.confidence.fillna(3) <= 2).values,
                   "confidence<=2, no road pixels": ((v.confidence.fillna(3) <= 2) & (v.is_road.fillna(0) != 1)).values}
        for sub, sel in subsets.items():
            ref, st = v.true_class.values[sel], v.stratum.values[sel]
            P = {k: p[sel] for k, p in pred.items()}
            d = boot(ref, P, st, W)
            for k, p in P.items():
                mf, f1, ua, pa = weighted(ref, p, st, W)
                rows.append({"subset": sub, "model": k, "n": int(sel.sum()), "macro_F1": mf,
                             "lo": np.percentile(d[k], 2.5), "hi": np.percentile(d[k], 97.5),
                             **{f"F1_{c}": f1[c - 1] for c in CL}, "UA_2": ua[1], "PA_2": pa[1]})
            for a, b in [("year_2023", "osm2026_2023"), ("pooled", "osm2026_2023"), ("pooled", "year_2023")]:
                if a in P and b in P:
                    dd = d[a] - d[b]
                    prs.append({"subset": sub, "comparison": f"{a} minus {b}",
                                "diff_macro_F1": weighted(ref, P[a], st, W)[0] - weighted(ref, P[b], st, W)[0],
                                "lo": np.percentile(dd, 2.5), "hi": np.percentile(dd, 97.5)})
        hs, hp = pd.DataFrame(rows), pd.DataFrame(prs)
        hs.to_csv(OUT / "handlabel_scores.csv", index=False); hp.to_csv(OUT / "handlabel_paired.csv", index=False)
        rep += ["## Hand labels (2023, stratum-weighted macro-F1, 95% stratified bootstrap)\n",
                md(hs) + "\n", "Paired differences (same bootstrap draws):\n", md(hp) + "\n",
                "Reference: Ethan's 20 m PHYS model with undated labels scored 0.622 [0.553, 0.692]; "
                "the 10 m PHYS model 0.627 (experiments/res100/RESULTS.md).\n"]
    if (OUT / "cv_scores.csv").exists():
        rep += ["## Spatial CV on OSM labels (5-fold, 12 km blocks; each model on its own labels)\n",
                md(pd.read_csv(OUT / "cv_scores.csv")) + "\n"]
        cp = pd.read_csv(OUT / "cv_paired.csv")
        if len(cp):
            rep += ["Pooled vs year models on the same rows and labels (paired block bootstrap):\n", md(cp) + "\n"]
        rep += ["Scores against different label sets are not comparable with each other; the hand labels are "
                "the common yardstick.\n"]
    if (OUT / "map_stats.csv").exists():
        ms = pd.read_csv(OUT / "map_stats.csv")
        rep += ["## Map shares and year-to-year stability\n",
                md(ms[ms.stat == "class share"].dropna(axis=1, how="all").drop(columns="stat")) + "\n",
                md(ms[ms.stat != "class share"].dropna(axis=1, how="all"), 4) + "\n",
                "Real development is about 0.1% of HMDA per year, so most changed cells are model noise. "
                "Lower is better; built -> open should be near zero.\n"]
    rep += ["## Caveats\n",
            "- The land-cover parts of the labels (Dynamic World 2023, WorldCover 2021, JRC to 2021, GHS-BUILT-C "
            "2018) are the same for every year; only the OSM part and the water rule are dated.\n",
            "- OSM history also reflects mapping effort: fewer polygons in 2017 means fewer labels, not less land use.\n",
            "- The hand labels are for 2023 only, so 2017 and 2020 are checked by OSM-label CV and map stability only.\n",
            "- Hand labels are scored at the cell containing each 10 m test point, not relabelled at 20 m.\n"]
    (OUT / "RESULTS.md").write_text("\n".join(rep), encoding="utf-8")
    if hs is not None:
        pd.set_option("display.width", 220)
        log("\n" + hs.round(3).to_string(index=False) + "\n" + hp.round(3).to_string(index=False))
    log(f"wrote {OUT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
